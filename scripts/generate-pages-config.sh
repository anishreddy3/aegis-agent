#!/usr/bin/env bash
# Writes web/config.js from AEGIS_DEFAULT_API for Cloudflare Pages deploy.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${ROOT}/web/config.js"
API="${AEGIS_DEFAULT_API:-}"

if [[ -z "$API" ]]; then
  if [[ -f "$OUT" ]] && grep -qE 'apiUrl: "https?://[^"]+' "$OUT" 2>/dev/null; then
    echo "AEGIS_DEFAULT_API unset — keeping existing web/config.js"
    exit 0
  fi
  echo "Set AEGIS_DEFAULT_API to your tunnel URL, e.g.:"
  echo "  AEGIS_DEFAULT_API=https://abc.trycloudflare.com make pages-deploy"
  exit 1
fi

API="${API%/}"
cat >"$OUT" <<EOF
// Generated by scripts/generate-pages-config.sh — do not edit by hand
window.AEGIS_CONFIG = {
  apiUrl: "${API}",
};
EOF
echo "Wrote ${OUT} → ${API}"
